import { GENERATION_INPUT_INVALID_CODE } from "./admissionRejectionHints";

// 「这一次 generate / 付费门摆哪几镜」**唯一**的一条规则（2026-10-27，设计卡 docs/plan/2026-10-27-shot-scope-undecided.md §三）。
//
// ── 它在解决哪个真实摩擦 ──
//
// 以前 `shotIds?: string[]` 一个可选数组同时承载「点名了」和「没点名 = 让系统按事实决定」，缺省由每扇门自己补，最省事的
// 缺省永远是「全部」：handler 把「没点名」翻译成「点名全部」，付费门卡一关就封「没封过的全部」，reducer 再各留一份回退。
// 结果是 Agent 说「剩下没点的也来」，卡上却摆回了正在生成的那一镜；「直接生成」档替用户再决一次，同一镜花两次钱。
//
// 用户 2026-10-27 拍板：不点名 = **只重摆最近一张卡（开着或已关）上还没定的镜**；一镜不剩就拒，拒绝要告诉模型下一步。
// 事实只从出价账来（`generationPresentationOutcome`）；没有出价账的门（文稿方案、用户的选择）显式传 `NO_CURRENT_OFFER`。
// 纯函数，主进程与渲染层共用；拒绝是 `GenerationScopeRefusal`，码就是 `generation_input_invalid`，正文是写给模型看的。

/** 最近一次出价（开着或已关）上每一镜的结局。只从出价账的唯一读口 `generationPresentationOutcome` 来。 */
export type OfferOutcomeFacts = Readonly<{
  generating: readonly string[];
  failedBeforeSending: readonly string[];
  removed: readonly string[];
  takenByCanvas: readonly string[];
  undecided: ReadonlyArray<Readonly<{ shotId: string }>>;
}>;

/** 有一次出价（最近那张卡），或者从没出过价。调用方必须明说，`undefined` 混不过去。 */
export type CurrentOfferFacts =
  | Readonly<{ kind: "offer"; outcome: OfferOutcomeFacts }>
  | Readonly<{ kind: "no-current-offer" }>;

export const NO_CURRENT_OFFER: CurrentOfferFacts = Object.freeze({ kind: "no-current-offer" });

/** 出价账读口的结果 → 规则的输入。`generationPresentationOutcome` 只在从没出过价时是 `undefined`。 */
export function currentOfferFrom(outcome: OfferOutcomeFacts | undefined): CurrentOfferFacts {
  return outcome ? { kind: "offer", outcome } : NO_CURRENT_OFFER;
}

/** present = Agent 的 `generate`（点名可以是计划里任何一镜）；gate = 付费门（只能封此刻还能封的镜，外部宿主点不了名）。 */
export type GenerationScopeDoor = "present" | "gate";

/** 范围不成立：码是 `generation_input_invalid`，正文是我们自己写给模型的一句可行动的话（适配器原样放行）。 */
export class GenerationScopeRefusal extends Error {
  readonly code = GENERATION_INPUT_INVALID_CODE;
  constructor(message: string) {
    super(message);
    this.name = "GenerationScopeRefusal";
  }
}

function nameableLine(nameable: readonly string[]): string {
  return nameable.length > 0 ? `Shots you can name: ${nameable.join(", ")}.` : "No shot of this draft can be named here right now.";
}

/**
 * 点名那一半：非空数组、每项非空字符串、不重复、都在 `nameable` 里；按 `nameable` 的顺序返回（原子：要么整份收下，要么整份拒）。
 * 付费门有一道门在等时，先拿它的结果和那道门盖的镜比（`resolveGateScope`）。
 */
export function resolveNamedGenerationShots(nameable: readonly string[], requested: unknown): string[] {
  const refuse = (why: string): never => { throw new GenerationScopeRefusal(`${why} ${nameableLine(nameable)}`); };
  if (!Array.isArray(requested)) return refuse("shotIds must be a list of shot ids, or left out.");
  if (requested.length === 0) return refuse("shotIds is empty: list at least one shot id, or leave shotIds out.");
  const named = new Set<string>();
  for (const value of requested) {
    if (typeof value !== "string" || !value.trim()) return refuse("shotIds has an entry that is not a shot id.");
    const shotId = value.trim();
    if (named.has(shotId)) return refuse(`shotIds names ${shotId} more than once; name each shot once.`);
    if (!nameable.includes(shotId)) return refuse(`${shotId} is not one of the shots you can name here.`);
    named.add(shotId);
  }
  return nameable.filter((shotId) => named.has(shotId));
}

const STATE_WORDS: ReadonlyArray<readonly [Exclude<keyof OfferOutcomeFacts, "undecided">, string]> = [
  ["generating", "generating"],
  ["failedBeforeSending", "failed before anything was sent"],
  ["removed", "removed by the user"],
  ["takenByCanvas", "generated by the user from the canvas"],
];

function onOffer(outcome: OfferOutcomeFacts): Set<string> {
  return new Set([...STATE_WORDS.flatMap(([state]) => outcome[state]), ...outcome.undecided.map((entry) => entry.shotId)]);
}

const GATE_NEXT_STEP = "This gate cannot pick shots: to generate shots again, start a new draft (nomi_operation_plan without operationId) and request its gate.";

/** 一镜不剩时的拒绝：每一镜现在怎样、卡外还有哪些、这扇门的下一步。 */
function nothingLeft(door: GenerationScopeDoor, planShotIds: readonly string[], currentOffer: CurrentOfferFacts): string {
  if (planShotIds.length === 0) return "This draft has no shots yet, so there is nothing to put on a card. Add shots to it first.";
  const present = (why: string) => `${why} To put shots on a card anyway, call generate again with shotIds naming them; give a shot that is generating another take only if the user asks for one. ${nameableLine(planShotIds)}`;
  if (currentOffer.kind === "no-current-offer") {
    return door === "present"
      ? present("No shot of this draft is waiting to be offered: every included shot was already sent to generation or removed by the user.")
      : `No shot of this draft is waiting to be sealed: every included shot is already sealed or was removed by the user, so there is nothing to seal. ${GATE_NEXT_STEP}`;
  }
  const { outcome } = currentOffer;
  const states = planShotIds.flatMap((shotId) => {
    const state = STATE_WORDS.find(([key]) => outcome[key].includes(shotId));
    if (state) return [`${shotId}: ${state[1]}`];
    // 卡上还没定、这扇门此刻却摆不了 / 封不了（付费门：已经封过；generate：已经不在这一批里）。
    return outcome.undecided.some((entry) => entry.shotId === shotId) ? [`${shotId}: ${door === "gate" ? "already sealed" : "no longer in this batch"}`] : [];
  });
  const card = onOffer(outcome);
  const outside = planShotIds.filter((shotId) => !card.has(shotId));
  const notOnCard = outside.length > 0 ? ` Shots not on that card: ${outside.join(", ")}.` : "";
  return door === "present"
    ? present(`Nothing on the latest card for this draft is still waiting for the user's decision (${states.join("; ")}).${notOnCard} Leaving shotIds out only re-offers shots that are still undecided on the latest card.`)
    : `Nothing on the latest card for this draft is still waiting for a decision (${states.join("; ")}), so there is nothing to seal.${notOnCard} ${GATE_NEXT_STEP}`;
}

/**
 * 这一次摆 / 封哪几镜：
 *   · 点名了 → 就是这几镜（present 门：计划里任何一镜，重试照常；gate 门：此刻还能封的）；
 *   · 没点名 + 有当前出价 → 那张卡上还没定、这扇门此刻又能摆 / 能封的镜；
 *   · 没点名 + 没有当前出价 → `offerable`（第一次出价 / 第一次封整份草稿）；
 *   · 一镜不剩 → 拒绝（不回退成「全部」）。结果按计划顺序。
 */
export function resolveUndecidedGenerationShotScope(input: Readonly<{
  door: GenerationScopeDoor;
  /** 计划顺序。 */
  planShotIds: readonly string[];
  /** 原样的 `shotIds`；`undefined` = 没点名。 */
  requested: unknown;
  currentOffer: CurrentOfferFacts;
  /** 这扇门此刻能摆 / 能封的镜。 */
  offerable: readonly string[];
}>): string[] {
  const { door, planShotIds, requested, currentOffer, offerable } = input;
  if (requested !== undefined) {
    return resolveNamedGenerationShots(door === "present" ? planShotIds : planShotIds.filter((shotId) => offerable.includes(shotId)), requested);
  }
  const scope = currentOffer.kind === "offer"
    ? planShotIds.filter((shotId) => offerable.includes(shotId) && currentOffer.outcome.undecided.some((entry) => entry.shotId === shotId))
    : planShotIds.filter((shotId) => offerable.includes(shotId));
  if (scope.length > 0) return scope;
  throw new GenerationScopeRefusal(nothingLeft(door, planShotIds, currentOffer));
}

/**
 * present 回执的 `shots` = 这一次出价摆的镜（结局里五种状态的并集，按计划顺序；单镜旧形态 = 顶层候选那一镜）。
 * 读不到出价是宿主自己的缺陷，不编一个。
 */
export function shotsOnOffer(operation: Readonly<{
  candidate: Readonly<{ candidateId: string }>;
  shots?: ReadonlyArray<Readonly<{ shotId: string }>>;
  presentationOutcome?: OfferOutcomeFacts;
}>): string[] {
  const outcome = operation.presentationOutcome;
  if (!outcome) throw new Error("generation_offer_missing: presenting left no offer to read");
  const card = onOffer(outcome);
  const planShotIds = operation.shots?.length ? operation.shots.map((shot) => shot.shotId) : [operation.candidate.candidateId];
  return planShotIds.filter((shotId) => card.has(shotId));
}
