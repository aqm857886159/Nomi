import { describe, expect, it } from "vitest";

import {
  GenerationScopeRefusal,
  NO_CURRENT_OFFER,
  currentOfferFrom,
  resolveNamedGenerationShots,
  resolveUndecidedGenerationShotScope,
  shotsOnOffer,
  type OfferOutcomeFacts,
} from "./generationShotScope";
import { GENERATION_INPUT_INVALID_CODE } from "./admissionRejectionHints";

// 「这一次 generate / 封印摆哪几镜」唯一那条规则的输入表（设计卡 docs/plan/2026-10-27-shot-scope-undecided.md §三，★9 A14）。
// 每一行 × 两扇门（present = Agent 的 generate；gate = 外部宿主的付费门）。

const PLAN = ["shot-1", "shot-2", "shot-3", "shot-4"] as const;

function outcome(partial: Partial<Record<Exclude<keyof OfferOutcomeFacts, "undecided">, readonly string[]>> & { undecided?: readonly string[] } = {}): OfferOutcomeFacts {
  return {
    generating: partial.generating ?? [],
    failedBeforeSending: partial.failedBeforeSending ?? [],
    removed: partial.removed ?? [],
    takenByCanvas: partial.takenByCanvas ?? [],
    undecided: (partial.undecided ?? []).map((shotId) => ({ shotId })),
  };
}

function refusalOf(run: () => unknown): GenerationScopeRefusal {
  try {
    run();
  } catch (error) {
    if (error instanceof GenerationScopeRefusal) return error;
    throw error;
  }
  throw new Error("expected a GenerationScopeRefusal");
}

describe.each(["present", "gate"] as const)("door %s", (door) => {
  const scope = (requested: unknown, offer: Parameters<typeof currentOfferFrom>[0], offerable: readonly string[] = PLAN) =>
    resolveUndecidedGenerationShotScope({ door, planShotIds: PLAN, requested, currentOffer: currentOfferFrom(offer), offerable });

  it("没点名 + 有当前出价（开着或已关都一样）：只取最近一张卡上还没定、此刻又能摆 / 能封的，按计划顺序", () => {
    expect(scope(undefined, outcome({ undecided: ["shot-3", "shot-1"], generating: ["shot-2"] }))).toEqual(["shot-1", "shot-3"]);
    expect(scope(undefined, outcome({ undecided: ["shot-2", "shot-3"] }), ["shot-3"])).toEqual(["shot-3"]);
  });

  it("没点名 + 有当前出价、一镜都不剩：拒绝（码 generation_input_invalid），逐镜说状态、点出卡外的镜，给这扇门的下一步", () => {
    const refusal = refusalOf(() => scope(undefined, outcome({ generating: ["shot-1"], removed: ["shot-2"], failedBeforeSending: ["shot-3"] })));
    expect(refusal.code).toBe(GENERATION_INPUT_INVALID_CODE);
    expect(refusal.message).toContain("shot-1: generating");
    expect(refusal.message).toContain("shot-2: removed by the user");
    expect(refusal.message).toContain("shot-3: failed before anything was sent");
    expect(refusal.message).toContain("Shots not on that card: shot-4.");
    if (door === "present") {
      expect(refusal.message).toContain("call generate again with shotIds naming them");
      expect(refusal.message).toContain("Shots you can name: shot-1, shot-2, shot-3, shot-4.");
    } else {
      expect(refusal.message).toContain("nothing to seal");
      expect(refusal.message).toContain("start a new draft (nomi_operation_plan without operationId)");
    }
  });

  it("没点名 + 有当前出价、卡上没定的镜此刻不能摆 / 封：同样拒绝，不回退成 offerable 全集", () => {
    const refusal = refusalOf(() => scope(undefined, outcome({ undecided: ["shot-2"], takenByCanvas: ["shot-1"] }), ["shot-3", "shot-4"]));
    expect(refusal.message).toContain("shot-1: generated by the user from the canvas");
    expect(refusal.message).toContain(door === "gate" ? "shot-2: already sealed" : "shot-2: no longer in this batch");
  });

  it("没点名 + 没有当前出价：offerable 全部（第一次出价 / 第一次封整份草稿）；offerable 为空就拒", () => {
    expect(resolveUndecidedGenerationShotScope({ door, planShotIds: PLAN, requested: undefined, currentOffer: NO_CURRENT_OFFER, offerable: ["shot-4", "shot-2"] }))
      .toEqual(["shot-2", "shot-4"]);
    const refusal = refusalOf(() => resolveUndecidedGenerationShotScope({ door, planShotIds: PLAN, requested: undefined, currentOffer: NO_CURRENT_OFFER, offerable: [] }));
    expect(refusal.message).toMatch(door === "present" ? /waiting to be offered[\s\S]*call generate again with shotIds/ : /nothing to seal[\s\S]*start a new draft/);
  });

  it("点名：按计划顺序返回，不扩大；present 门不收窄成「只许没定的」，gate 门只认此刻能封的", () => {
    const offer = outcome({ undecided: ["shot-2"], generating: ["shot-1"] });
    if (door === "present") expect(scope(["shot-3", "shot-1"], offer, ["shot-2"])).toEqual(["shot-1", "shot-3"]);
    else {
      expect(scope(["shot-3", "shot-2"], offer, ["shot-2", "shot-3"])).toEqual(["shot-2", "shot-3"]);
      expect(refusalOf(() => scope(["shot-1"], offer, ["shot-2", "shot-3"])).message).toBe(
        "shot-1 is not one of the shots you can name here. Shots you can name: shot-2, shot-3.");
    }
  });

  it.each([
    [null, /shotIds must be a list of shot ids, or left out/],
    ["shot-1", /shotIds must be a list of shot ids, or left out/],
    [[], /shotIds is empty/],
    [["shot-1", ""], /an entry that is not a shot id/],
    [["shot-1", 7], /an entry that is not a shot id/],
    [["shot-1", " shot-1 "], /names shot-1 more than once/],
    [["ghost"], /ghost is not one of the shots you can name here/],
  ])("点名无效 %j → 拒绝，列出可以点的", (requested, says) => {
    const refusal = refusalOf(() => scope(requested, outcome({ undecided: ["shot-1"] })));
    expect(refusal.code).toBe(GENERATION_INPUT_INVALID_CODE);
    expect(refusal.message).toMatch(says);
    expect(refusal.message).toContain("Shots you can name: shot-1, shot-2, shot-3, shot-4.");
  });
});

describe("resolveNamedGenerationShots / shotsOnOffer / 计划为空", () => {
  it("点名那一半：去掉首尾空白、按可点名的顺序返回", () => {
    expect(resolveNamedGenerationShots(PLAN, [" shot-4", "shot-2 "])).toEqual(["shot-2", "shot-4"]);
    expect(refusalOf(() => resolveNamedGenerationShots([], ["shot-1"])).message).toBe(
      "shot-1 is not one of the shots you can name here. No shot of this draft can be named here right now.");
  });

  it("回执 = 这一次出价摆的镜：五种状态的并集，按计划顺序；没有出价是宿主的缺陷，不编一个", () => {
    const draft = { candidate: { candidateId: "shot-1" }, shots: PLAN.map((shotId) => ({ shotId })) };
    expect(shotsOnOffer({ ...draft, presentationOutcome: outcome({ undecided: ["shot-4"], generating: ["shot-2"], removed: ["shot-1"] }) }))
      .toEqual(["shot-1", "shot-2", "shot-4"]);
    expect(shotsOnOffer({ candidate: { candidateId: "single" }, presentationOutcome: outcome({ undecided: ["single"] }) }), "单镜旧形态 = 顶层候选那一镜")
      .toEqual(["single"]);
    expect(() => shotsOnOffer(draft)).toThrow(/no offer/);
  });

  it("计划里一镜都没有：拒绝并说先加镜头", () => {
    const refusal = refusalOf(() => resolveUndecidedGenerationShotScope({ door: "present", planShotIds: [], requested: undefined, currentOffer: NO_CURRENT_OFFER, offerable: [] }));
    expect(refusal.message).toBe("This draft has no shots yet, so there is nothing to put on a card. Add shots to it first.");
  });
});
