// Compile the official 2020-12 meta-schema once; production never generates code from strings.
// https://ajv.js.org/standalone.html and https://ajv.js.org/security.html#content-security-policy
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standalone from 'ajv/dist/standalone/index.js'
import { build } from 'vite'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outputBase = path.join(root, 'electron/shared/agentCapabilities/modelSchemaMetaValidator.generated')
export const outputFiles = { cjs: `${outputBase}.cjs`, esm: `${outputBase}.mjs` }

export async function generateMetaValidators() {
  const ajv = new Ajv2020({ strict: false, allErrors: true, validateFormats: false, code: { source: true, esm: true } })
  const code = standalone(ajv, ajv.getSchema('https://json-schema.org/draft/2020-12/schema'))
    .replace(/export const validate = \w+;/, '')
    .replace(/const (\w+) = require\("([^"]+)"\)\.default;/g,
      (_match, name, module) => `import ${name} from ${JSON.stringify(require.resolve(`${module}.js`))};`)
  // Bundle maintained runtime helpers too; no production dependency or dynamic compilation remains.
  const id = '\0nomi-schema-meta-validator.mjs'
  const bundled = await build({
    root, configFile: false, logLevel: 'silent',
    plugins: [{ name: 'official-schema-standalone', resolveId: name => name.endsWith('nomi-schema-meta-validator') ? id : null,
      load: name => name === id ? code : null }],
    build: { write: false, minify: true, target: 'es2022',
      lib: { entry: 'nomi-schema-meta-validator', formats: ['cjs', 'es'], fileName: format => format === 'es' ? 'meta.mjs' : 'meta.cjs' },
    },
  })
  const outputs = Array.isArray(bundled) ? bundled : [bundled]
  const chunks = outputs.flatMap(result => result.output).filter(item => item.type === 'chunk')
  if (chunks.length !== 2 || chunks.some(chunk => chunk.imports.length)) throw new Error('Both module formats must be self-contained')
  const license = [require.resolve('ajv/LICENSE'), require.resolve('fast-deep-equal/LICENSE', { paths: [path.dirname(require.resolve('ajv/package.json'))] })]
    .map(file => fs.readFileSync(file, 'utf8')).join('\n')
  const header = `/* @generated by scripts/gen-model-schema-meta-validator.mjs; DO NOT EDIT.\nJSON Schema 2020-12 official meta-schema; Ajv ${require('ajv/package.json').version}.\nBundled Ajv / fast-deep-equal licensing:\n${license}\n*/\n/* eslint-disable -- Generated validator; parity and no-code-generation tests own this artifact. */\n`
  return Object.fromEntries(chunks.map(chunk => [chunk.fileName.endsWith('.mjs') ? 'esm' : 'cjs', header + chunk.code]))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const code = await generateMetaValidators()
  for (const format of ['cjs', 'esm']) {
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(outputFiles[format], 'utf8') !== code[format]) throw new Error('Generated meta validator is stale; rerun its generator')
    } else fs.writeFileSync(outputFiles[format], code[format])
  }
  if (process.argv.includes('--check')) console.log('Generated JSON Schema 2020-12 module formats are current.')
}
