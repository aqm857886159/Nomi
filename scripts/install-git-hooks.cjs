#!/usr/bin/env node
/**
 * 在 pnpm install (postinstall) 时把 Git hooks 写入 Git 配置的 hooks 目录。
 * 已存在则覆盖（保持 source-of-truth 在 scripts/）。
 *
 * Git hooks 必须保持边界明确：pre-commit 先运行现有敏感数据扫描，再
 * 调用只读、限时的 Ponytail Codex 适配器；pre-push 读取 Git 提供的
 * outgoing refs 并调用同一适配器。适配器失败就阻止操作。
 *
 * linked worktree 且启用 extensions.worktreeConfig 时使用该 worktree 的
 * 专属 hooks 目录，避免安装一个分支时改坏其他并行分支；无法隔离时跳过。
 * 在非 git 工作目录（如 CI 缓存还原阶段）静默退出，不报错。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { execFileSync, execSync } = require('node:child_process')

const REPO_ROOT = path.resolve(__dirname, '..')

// 装的 hook（source-of-truth 在 scripts/，随 git 走）。顺序是契约：
//   · commit-msg = 原有提交信息进度校验。
//   · pre-commit = 原有敏感数据扫描 → Ponytail review（staged diff）。
//   · pre-push = Ponytail review（outgoing ref diff）。
const HOOKS = Object.freeze([
  Object.freeze({
    name: 'commit-msg',
    commands: Object.freeze([
      Object.freeze({ target: 'scripts/check-progress-update.cjs', passArgs: true }),
    ]),
  }),
  Object.freeze({
    name: 'pre-commit',
    commands: Object.freeze([
      Object.freeze({ target: 'scripts/check-no-secrets.mjs', passArgs: true }),
      Object.freeze({ target: 'scripts/ponytail-review-hook.mjs', args: ['--scope', 'staged'] }),
    ]),
  }),
  Object.freeze({
    name: 'pre-push',
    commands: Object.freeze([
      Object.freeze({ target: 'scripts/ponytail-review-hook.mjs', args: ['--scope', 'push'], passArgs: true }),
    ]),
  }),
])

function shellQuote(value) {
  // Hook arguments are static source-controlled values. Keep this quote helper
  // strict anyway, so a future target cannot accidentally become shell syntax.
  return `"${String(value).replace(/[\\"$`]/g, '\\$&')}"`
}

function renderCommand(command, { final = false } = {}) {
  // Keep the runtime ROOT variable expandable while quoting the target path.
  // Passing the whole expression through shellQuote would escape `$ROOT` and
  // make the generated hook look for a literal directory named "$ROOT".
  const target = String(command.target).replace(/[\\"$`]/g, '\\$&')
  const args = [`"$ROOT/${target}"`]
  for (const argument of command.args || []) args.push(shellQuote(argument))
  if (command.passArgs) args.push('"$@"')
  return `${final ? 'exec ' : ''}node ${args.join(' ')}`
}

function renderHookContent(hook) {
  if (!hook || !Array.isArray(hook.commands) || hook.commands.length === 0) {
    throw new TypeError('Hook definition must contain at least one command')
  }
  const commandLines = hook.commands.map((command, index) => renderCommand(command, {
    final: index === hook.commands.length - 1,
  }))
  const optionalPonytailGuard = hook.name === 'pre-push'
    ? '[ -f "$ROOT/scripts/ponytail-review-hook.mjs" ] || exit 0\n'
    : ''
  return `#!/usr/bin/env bash
# Auto-generated by scripts/install-git-hooks.cjs — do not edit.
set -e
ROOT="$(git rev-parse --show-toplevel)"
${optionalPonytailGuard}${commandLines.join('\n')}
`
}

function resolveHookInfo(repoRoot, exec = execSync) {
  let gitDir
  let commonDir
  let configuredHooksPath
  try {
    gitDir = exec('git rev-parse --git-dir', {
      cwd: repoRoot,
      encoding: 'utf8',
    }).trim()
    commonDir = exec('git rev-parse --git-common-dir', {
      cwd: repoRoot,
      encoding: 'utf8',
    }).trim()
    configuredHooksPath = exec('git rev-parse --git-path hooks', {
      cwd: repoRoot,
      encoding: 'utf8',
    }).trim()
  } catch (_err) {
    return null
  }
  if (!gitDir || !commonDir) return null

  // git-dir/commonDir 可能是相对路径，相对于 repoRoot。
  const absGitDir = path.isAbsolute(gitDir) ? path.resolve(gitDir) : path.resolve(repoRoot, gitDir)
  const absCommonDir = path.isAbsolute(commonDir) ? commonDir : path.resolve(repoRoot, commonDir)
  const linkedWorktree = path.resolve(absGitDir) !== path.resolve(absCommonDir)

  // Linked worktrees normally share $commonDir/hooks.  When Git's
  // worktreeConfig extension is enabled, keep this worktree's hook files and
  // core.hooksPath local so installing a new branch cannot break another one.
  if (linkedWorktree) {
    let worktreeConfig = false
    try {
      worktreeConfig = exec('git config --bool extensions.worktreeConfig', {
        cwd: repoRoot,
        encoding: 'utf8',
      }).trim() === 'true'
    } catch (_err) {
      worktreeConfig = false
    }
    if (worktreeConfig) {
      return { hookDir: path.join(absGitDir, 'hooks'), linkedWorktree: true, configureWorktreePath: true }
    }
    // Do not write a branch-specific hook into a shared common directory when
    // Git cannot isolate the linked worktree's config. The next install on a
    // worktree with extensions.worktreeConfig enabled can install it safely.
    return { hookDir: path.join(absCommonDir, 'hooks'), linkedWorktree: true, configureWorktreePath: false }
  }

  const hookDir = configuredHooksPath
    ? (path.isAbsolute(configuredHooksPath) ? path.resolve(configuredHooksPath) : path.resolve(repoRoot, configuredHooksPath))
    : path.join(absCommonDir, 'hooks')
  return { hookDir, linkedWorktree: false, configureWorktreePath: false }
}

function resolveHookDir(repoRoot, exec = execSync) {
  return resolveHookInfo(repoRoot, exec)?.hookDir ?? null
}

function installHooks({ repoRoot = REPO_ROOT, exec = execSync, execFile = execFileSync, logger = console } = {}) {
  const info = resolveHookInfo(repoRoot, exec)
  if (!info) {
    logger.log('Not a git repository. Skipping hook install.')
    return { installed: [], skipped: true }
  }

  if (info.linkedWorktree && !info.configureWorktreePath) {
    logger.warn('Linked worktree has no worktreeConfig isolation. Skipping shared hook install.')
    return { installed: [], skipped: true, reason: 'worktree_hooks_unavailable' }
  }

  const hookDir = info.hookDir
  if (!fs.existsSync(hookDir)) {
    try {
      fs.mkdirSync(hookDir, { recursive: true })
    } catch (_err) {
      logger.log('Cannot create hook dir. Skipping.')
      return { installed: [], skipped: true }
    }
  }

  // Create the isolated directory before changing worktree config.  A failed
  // mkdir must never leave Git pointing at a hooks path that does not exist.
  if (info.configureWorktreePath) {
    try {
      execFile('git', ['config', '--worktree', 'core.hooksPath', hookDir], {
        cwd: repoRoot,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      })
    } catch (err) {
      logger.warn(`Cannot isolate linked worktree hooks. Skipping: ${err.message}`)
      return { installed: [], skipped: true, reason: 'worktree_hooks_unavailable' }
    }
  }

  const installed = []
  for (const hook of HOOKS) {
    const hookPath = path.join(hookDir, hook.name)
    const hookContent = renderHookContent(hook)
    try {
      fs.writeFileSync(hookPath, hookContent)
      fs.chmodSync(hookPath, 0o755)
      installed.push(hook.name)
      const targets = hook.commands.map(({ target }) => target).join(' → ')
      logger.log(`Installed ${hook.name} hook → ${targets}`)
    } catch (err) {
      // postinstall 不阻塞 pnpm install；某个 hook 装失败不影响其余
      logger.warn(`Failed to install ${hook.name} hook: ${err.message}`)
    }
  }
  return { installed, skipped: false, hookDir }
}

module.exports = {
  HOOKS,
  renderHookContent,
  resolveHookDir,
  installHooks,
}

if (require.main === module) installHooks()
