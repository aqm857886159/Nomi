#!/usr/bin/env node
/**
 * 在 pnpm install (postinstall) 时把 Git hooks 写入 .git/hooks/。
 * 已存在则覆盖（保持 source-of-truth 在 scripts/）。
 *
 * 在非 git 工作目录（如 CI 缓存还原阶段）静默退出，不报错。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { execSync } = require('node:child_process')

const repoRoot = path.resolve(__dirname, '..')

let commonDir
try {
  commonDir = execSync('git rev-parse --git-common-dir', {
    cwd: repoRoot,
    encoding: 'utf8',
  }).trim()
} catch (_err) {
  console.log('Not a git repository. Skipping hook install.')
  process.exit(0)
}

// 装的 hook（source-of-truth 在 scripts/，随 git 走）。
//  · commit-msg = 提交信息进度校验。
//  · pre-commit = 先运行 Ponytail over-engineering review，再扫敏感数据。
//  · pre-push = 对 outgoing ref 范围运行同一份 Ponytail review。
const HOOKS = [
  { name: 'commit-msg', commands: ['scripts/check-progress-update.cjs "$@"'] },
  { name: 'pre-commit', commands: ['scripts/ponytail-review-hook.mjs --scope staged', 'scripts/check-no-secrets.mjs "$@"'] },
  { name: 'pre-push', commands: ['scripts/ponytail-review-hook.mjs --scope push'] },
]

function renderHook({ commands }) {
  const lines = [
    '#!/usr/bin/env bash',
    '# Auto-generated by scripts/install-git-hooks.cjs — do not edit.',
    'set -euo pipefail',
    'ROOT="$(git rev-parse --show-toplevel)"',
  ]
  lines.push(...commands.map((command) => {
    const [, target, args = ''] = command.match(/^(\S+)(.*)$/) || []
    return `node "$ROOT/${target}"${args}`
  }))
  lines.push('')
  return lines.join('\n')
}

function installHooks({ root = repoRoot, commonDir: common = commonDir } = {}) {
  const absDir = path.isAbsolute(common) ? common : path.join(root, common)
  const targetDir = path.join(absDir, 'hooks')
  if (!fs.existsSync(targetDir)) {
    try {
      fs.mkdirSync(targetDir, { recursive: true })
    } catch (_err) {
      console.log('Cannot create hook dir. Skipping.')
      return
    }
  }

  for (const { name, commands } of HOOKS) {
    const hookPath = path.join(targetDir, name)
    const hookContent = renderHook({ commands })
    try {
      fs.writeFileSync(hookPath, hookContent)
      fs.chmodSync(hookPath, 0o755)
      console.log(`Installed ${name} hook → ${commands.join(' → ')}`)
    } catch (err) {
      // postinstall 不阻塞 pnpm install；某个 hook 装失败不影响其余
      console.warn(`Failed to install ${name} hook: ${err.message}`)
    }
  }
}

if (require.main === module) installHooks()

module.exports = { HOOKS, renderHook, installHooks }
