// 把档案(electron/shared/modelArchetypes)的方式清单抽成纯数据，桥接给 electron。
// 无界面缺参兜底的默认值表、size 比例语义表、身份表已改成用时从档案现算（electron/shared/modelArchetypes/catalogFacts.ts），不再生成。
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MODEL_ARCHETYPES } from "../electron/shared/modelArchetypes/builtInCatalog.ts";
import { modeTransportFor } from "../electron/shared/videoCapabilities/modeTransport.ts";

type ModeManifest = Record<string, {
  defaultModeId: string;
  modes: Record<string, string>;
}>;
/**
 * 主进程脚本派发只需要确认「这个 modeId 是否属于该档案、走哪个 taskKind」。
 * 这里从完整档案生成最窄清单，避免 Electron 反向 import renderer 源码，也不在主进程
 * 复制 slots/params 等能力语义。用户自定义能力契约是运行时数据，另由主进程读取其显式投影。
 *
 * **供应商无关（传 null）是有意的**：本清单只服务用户自定义 custom-call 脚本派发与发布面
 * （见 electron/shared/capabilityModeManifest.ts 的消费点），那条路上的模型是用户自建的单供应商
 * 条目，不会带 vendorTransportTaskKind 覆盖。故这里取的是「未特化」的桶，与消费侧拿不到 vendorKey
 * 的事实一致——不假装知道供应商，也不悄悄用某一家的特化值当通用值。
 */
export function buildArchetypeModeManifest(): ModeManifest {
  const out: ModeManifest = {};
  for (const arch of MODEL_ARCHETYPES) {
    out[arch.id] = {
      defaultModeId: arch.defaultModeId,
      modes: Object.fromEntries(
        arch.modes.map((mode) => [mode.id, modeTransportFor(mode, arch, null)]),
      ),
    };
  }
  return out;
}

const BANNER = "// @generated by scripts/gen-archetype-wire-defaults.ts — 请勿手改（改档案后跑 pnpm gen:archetype-defaults）。\n";

/** 档案 id → kind（拆分生成文件用）。 */
function archetypeKindById(): Record<string, string> {
  return Object.fromEntries(MODEL_ARCHETYPES.map((arch) => [arch.id, arch.kind]));
}

const KIND_SLUG: Record<string, string> = {
  image: "image",
  video: "video",
  audio: "audio",
  model3d: "model3d",
};

/** 每片最多的 JSON 行数：低于文件体积门岗的黄牌（650），一片装不下就顺序续片（video2、video3 ...）。 */
const SHARD_MAX_LINES = 600;

/** 把一张 id→值 的表按 JSON 行数顺序切片；条目顺序保持，切点只看累计行数，所以结果可复现。 */
function chunkByLines<T>(table: Record<string, T>): Array<Record<string, T>> {
  const chunks: Array<Record<string, T>> = [];
  let current: Record<string, T> = {};
  let lines = 0;
  for (const [id, value] of Object.entries(table)) {
    const size = JSON.stringify({ [id]: value }, null, 2).split("\n").length - 2;
    if (lines > 0 && lines + size > SHARD_MAX_LINES) {
      chunks.push(current);
      current = {};
      lines = 0;
    }
    current[id] = value;
    lines += size;
  }
  if (Object.keys(current).length > 0) chunks.push(current);
  return chunks;
}

/** 按 kind 分组，每组再按行数续片：kind 的第一片叫 `image`，第二片 `image2`……。 */
function shardSlugs<T>(table: Record<string, T>): Array<{ slug: string; body: Record<string, T> }> {
  const kindById = archetypeKindById();
  const byKind: Record<string, Record<string, T>> = {};
  for (const [archetypeId, value] of Object.entries(table)) {
    const slug = KIND_SLUG[kindById[archetypeId]] ?? "other";
    byKind[slug] = byKind[slug] ?? {};
    byKind[slug][archetypeId] = value;
  }
  return Object.keys(KIND_SLUG)
    .concat("other")
    .filter((slug) => byKind[slug])
    .flatMap((slug) => chunkByLines(byKind[slug]).map((body, index) => ({ slug: index === 0 ? slug : `${slug}${index + 1}`, body })));
}

/** 模式清单同样按 kind 分片（`archetypeModes.<slug>.generated.ts`），出口 archetypeModes.generated.ts 合并。 */
export function renderModesShards(manifest: ModeManifest): Array<{ file: string; content: string }> {
  return shardSlugs(manifest).map(({ slug, body }) => ({
    file: `archetypeModes.${slug}.generated.ts`,
    content:
      `${BANNER}// 档案模式桥接（${slug} 分片）。合并出口在 archetypeModes.generated.ts。\n` +
      `export const ARCHETYPE_MODE_MANIFEST_${slug.toUpperCase()}: Record<string, { defaultModeId: string; modes: Record<string, string> }> = ${JSON.stringify(body, null, 2)};\n`,
  }));
}

export function renderModesFile(manifest: ModeManifest): string {
  const shards = renderModesShards(manifest).map((s) => s.file.replace(/\.ts$/, ""));
  const names = shards.map((f) => `ARCHETYPE_MODE_MANIFEST_${f.split(".")[1].toUpperCase()}`);
  return (
    `${BANNER}// 档案模式桥接：主进程只据此校验 modeId/taskKind；完整输入能力仍以 renderer 档案为真相源。\n` +
    `// 表体按 kind 分片（各 *.generated.ts），此处合并 —— 分片是为了不让单文件随档案数顶破 800 行巨壳门岗。\n` +
    shards.map((file, i) => `import { ${names[i]} } from "./${file}";\n`).join("") +
    `\nexport const ARCHETYPE_MODE_MANIFEST: Record<string, ${"{ defaultModeId: string; modes: Record<string, string> }"}> = {\n` +
    names.map((n) => `  ...${n},\n`).join("") +
    `};\n`
  );
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
export const normalizeGeneratedText = (value: string): string => value.replaceAll("\r\n", "\n");

if (isMain) {
  const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../electron/catalog");
  const outputs: Array<{ file: string; content: string }> = [
    ...renderModesShards(buildArchetypeModeManifest()),
    { file: "archetypeModes.generated.ts", content: renderModesFile(buildArchetypeModeManifest()) },
  ];
  if (process.argv.includes("--check")) {
    for (const { file, content } of outputs) {
      const target = path.join(dir, file);
      const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
      if (normalizeGeneratedText(existing) !== normalizeGeneratedText(content)) {
        console.error(`✗ ${file} 与档案不同步——跑 \`pnpm gen:archetype-defaults\` 重生成后提交。`);
        process.exit(1);
      }
    }
    console.log("✓ 档案默认参数桥接已同步。");
  } else {
    for (const { file, content } of outputs) fs.writeFileSync(path.join(dir, file), content);
    console.log(`wrote ${outputs.map((o) => o.file).join(", ")} (${MODEL_ARCHETYPES.length} archetypes)`);
  }
}
