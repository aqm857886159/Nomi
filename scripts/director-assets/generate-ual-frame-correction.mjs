#!/usr/bin/env node
/**
 * 生成 src/assets/director/ual/ual-frame-correction.json —— 导演台「规范骨轴修正表」。
 *
 * 为什么要有它：存档里的 boneRotations（骨局部欧拉度数）、FK 滑条、左右镜像（x,−y,−z）、视线分配、静态姿势预设与 AI 来导词表
 * 全部按 Mixamo（x-bot）骨的局部坐标轴写成；UAL 人偶的骨局部轴和它差 5°–180°（施工计划 docs/plan/2026-10-07-director-ual-mannequin.md §1 事实 2）。
 * 把 Mixamo 骨轴当「规范轴」，每根语义骨存两个常量四元数：
 *   rel       = 规范骨绑定世界朝向⁻¹ · UAL 骨绑定世界朝向       （偏移写入：O_ual = rel⁻¹ · O_规范 · rel）
 *   parentRel = 规范父骨绑定世界朝向⁻¹ · UAL 父骨绑定世界朝向   （局部换算：q_规范局部 = parentRel · q_ual局部 · rel⁻¹，视线分配用）
 * 朝向一律相对各自 glTF 场景根累积（两边都是 Y 向上、脸朝 +Z，见计划 §1 事实 4）。
 *
 * 规范骨架 x-bot.glb 在同一 PR 里被删掉（换 UAL，不留旧资产）；本脚本默认从 git 历史里取它（--xbot-rev，默认删除前的提交），
 * 也可 --xbot <文件> 直接给路径。three 只提供 GLTFLoader / Quaternion，表本身是我们旧存档的规范轴约定（领域数据，R5.4）。
 *
 * 用法：node scripts/director-assets/generate-ual-frame-correction.mjs [--check] [--xbot <path>] [--xbot-rev <git-rev>]
 *   --check  只比对入库文件与重新生成的结果，不一致退出 1
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import * as THREE from 'three'
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const UAL_FILE = 'src/assets/director/ual/ual-mannequin.glb'
const OUT_FILE = 'src/assets/director/ual/ual-frame-correction.json'
const XBOT_FILE = 'src/assets/x-bot.glb'
/** x-bot.glb 仍在仓库里的最后一个已知提交（施工计划提交）；删掉后从这里取 */
export const XBOT_DEFAULT_REV = '14e273cea'

/** 22 根语义骨：规范（Mixamo，去冒号）→ UAL（three 去点后的运行时名）。与 model/rigs.ts 的 MIXAMO / UAL 两张表同序同值，单测对账。 */
export const SEMANTIC_PAIRS = [
  ['hips', 'mixamorigHips', 'DEF-hips'],
  ['spine', 'mixamorigSpine', 'DEF-spine001'],
  ['spine1', 'mixamorigSpine1', 'DEF-spine002'],
  ['spine2', 'mixamorigSpine2', 'DEF-spine003'],
  ['neck', 'mixamorigNeck', 'DEF-neck'],
  ['head', 'mixamorigHead', 'DEF-head'],
  ['leftShoulder', 'mixamorigLeftShoulder', 'DEF-shoulderL'],
  ['leftArm', 'mixamorigLeftArm', 'DEF-upper_armL'],
  ['leftForeArm', 'mixamorigLeftForeArm', 'DEF-forearmL'],
  ['leftHand', 'mixamorigLeftHand', 'DEF-handL'],
  ['rightShoulder', 'mixamorigRightShoulder', 'DEF-shoulderR'],
  ['rightArm', 'mixamorigRightArm', 'DEF-upper_armR'],
  ['rightForeArm', 'mixamorigRightForeArm', 'DEF-forearmR'],
  ['rightHand', 'mixamorigRightHand', 'DEF-handR'],
  ['leftUpLeg', 'mixamorigLeftUpLeg', 'DEF-thighL'],
  ['leftLeg', 'mixamorigLeftLeg', 'DEF-shinL'],
  ['leftFoot', 'mixamorigLeftFoot', 'DEF-footL'],
  ['leftToeBase', 'mixamorigLeftToeBase', 'DEF-toeL'],
  ['rightUpLeg', 'mixamorigRightUpLeg', 'DEF-thighR'],
  ['rightLeg', 'mixamorigRightLeg', 'DEF-shinR'],
  ['rightFoot', 'mixamorigRightFoot', 'DEF-footR'],
  ['rightToeBase', 'mixamorigRightToeBase', 'DEF-toeR'],
]

function parseGlb(bytes) {
  const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength)
  return new Promise((resolve, reject) => new GLTFLoader().parse(buffer, '', resolve, reject))
}

/** 场景根 → 每个节点的累积朝向（只累积旋转，不受 x-bot 那层 0.01 缩放影响） */
function sceneRelativeQuaternions(scene) {
  const out = new Map([[scene, new THREE.Quaternion()]])
  scene.traverse((object) => {
    if (object === scene) return
    out.set(object, out.get(object.parent).clone().multiply(object.quaternion))
  })
  return out
}

function boneByName(scene, name) {
  let found = null
  scene.traverse((object) => {
    if (!found && object.isBone && object.name === name) found = object
  })
  if (!found) throw new Error(`bone not found: ${name}`)
  return found
}

const round = (q) => q.toArray().map((value) => Number(value.toFixed(6)) || 0)

export async function generateFrameCorrection({ xbotBytes, ualBytes }) {
  const [xbot, ual] = await Promise.all([parseGlb(xbotBytes), parseGlb(ualBytes)])
  const canonicalWorlds = sceneRelativeQuaternions(xbot.scene)
  const ualWorlds = sceneRelativeQuaternions(ual.scene)
  const bones = {}
  for (const [semantic, canonicalName, ualName] of SEMANTIC_PAIRS) {
    const canonical = boneByName(xbot.scene, canonicalName)
    const target = boneByName(ual.scene, ualName)
    const canonicalWorld = canonicalWorlds.get(canonical)
    const ualWorld = ualWorlds.get(target)
    const rel = canonicalWorld.clone().invert().multiply(ualWorld).normalize()
    const parentRel = canonicalWorlds.get(canonical.parent).clone().invert().multiply(ualWorlds.get(target.parent)).normalize()
    bones[semantic] = {
      canonicalBone: canonicalName,
      ualBone: ualName,
      canonicalBindWorld: round(canonicalWorld),
      ualBindWorld: round(ualWorld),
      rel: round(rel),
      parentRel: round(parentRel),
    }
  }
  return {
    $comment: 'Generated by scripts/director-assets/generate-ual-frame-correction.mjs; do not hand edit. Canonical frame = Mixamo x-bot.glb bind pose; quaternions are [x, y, z, w], scene-root relative.',
    canonicalSource: `${XBOT_FILE}@${XBOT_DEFAULT_REV}`,
    ualSource: UAL_FILE,
    bones,
  }
}

function readXbot(args) {
  const fileFlag = args.indexOf('--xbot')
  if (fileFlag !== -1) return fs.readFileSync(path.resolve(args[fileFlag + 1]))
  const local = path.join(ROOT, XBOT_FILE)
  if (fs.existsSync(local)) return fs.readFileSync(local)
  const revFlag = args.indexOf('--xbot-rev')
  const rev = revFlag !== -1 ? args[revFlag + 1] : XBOT_DEFAULT_REV
  return execFileSync('git', ['show', `${rev}:${XBOT_FILE}`], { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 })
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2)
  const table = await generateFrameCorrection({ xbotBytes: readXbot(args), ualBytes: fs.readFileSync(path.join(ROOT, UAL_FILE)) })
  const text = `${JSON.stringify(table, null, 2)}\n`
  const outPath = path.join(ROOT, OUT_FILE)
  if (args.includes('--check')) {
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== text) {
      console.error(`${OUT_FILE} 与重新生成的结果不一致`)
      process.exit(1)
    }
    console.log(`${OUT_FILE} 一致`)
  } else {
    fs.writeFileSync(outPath, text)
    console.log(`wrote ${OUT_FILE}`)
  }
}
