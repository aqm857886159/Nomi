/**
 * 一次产出的历史变体（设计合同 v6 §2.9，2026-09-05 用户拍板）。
 *
 * 为什么要有它：v5 的「重生成」把**不可逆的破坏性动作**藏在一枚看起来很轻的按钮后面——
 * 用户点它想的是"我再看一个别的可能"，不是"我要丢掉刚才那张"，但两者共用同一个按钮、同一个结果。
 * 更糟的是被顶掉的那张可能已被下一镜当首帧引用了。
 *
 * v6 的规则：**重生成 = 往抽屉里追加一版，不覆盖画面格；只有用户显式点「采用」，画面格才换。**
 *
 * ⚠️ 本轮（实验室优先）只定形状与交互，**不接持久化**：抽屉里的变体由调用方喂进来。
 * 落盘位置与清理策略（一镜生成 20 版之后磁盘怎么办）是下一刀的事，见合同 §9.3。
 */
export type ShotVariant = {
  /** 稳定 id（抽屉里的 key、采用/删除的寻址）。 */
  id: string
  url: string
  /** 这一版落地时自动拿到的 `@tag`（§2.10）——没被采用的变体也有，"这版适合下一镜"是真实用法。 */
  tag: string
  /** 生成这一版时的模型/模式快照（人话标签，抽屉里逐版可见）。 */
  modelLabel: string
  modeLabel: string
  /** 生成这一版时的提示词快照。 */
  prompt: string
  /** 落地时间（毫秒）——抽屉按时间倒序。 */
  createdAt: number
}

/** 时间倒序（最新的在最前）。抽屉与计数共用这一份排序，两处别各排各的。 */
export function orderedVariants(variants: readonly ShotVariant[]): ShotVariant[] {
  return [...variants].sort((a, b) => b.createdAt - a.createdAt)
}
